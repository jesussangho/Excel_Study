export function getFunctionById(id: string): ExcelFunction | undefined {
  return excelFunctions.find((f) => f.id === id);
}

export function getFunctionsByCategory(categoryId: string): ExcelFunction[] {
  return excelFunctions.filter((f) => f.category === categoryId);
}

export function searchFunctions(query: string): ExcelFunction[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return excelFunctions.filter(
    (f) =>
      f.name.toLowerCase().includes(q) ||
      f.kidExplanation.includes(q) ||
      f.keywords.some((k) => k.toLowerCase().includes(q)),
  );
}
